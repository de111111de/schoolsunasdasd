-- SCHOOLSUN: схема БД (совместима с H2 (MODE=PostgreSQL) и PostgreSQL)

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(190) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    full_name     VARCHAR(190) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    blocked       BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at    TIMESTAMP    NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_users_email ON users (email);

CREATE TABLE password_reset_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users (id),
    token      VARCHAR(64)  NOT NULL,
    expires_at TIMESTAMP    NOT NULL,
    used       BOOLEAN      NOT NULL DEFAULT FALSE
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_prt_token ON password_reset_tokens (token);

CREATE TABLE courses (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title           VARCHAR(190) NOT NULL,
    slug            VARCHAR(190) NOT NULL,
    description     TEXT,
    subject         VARCHAR(30)  NOT NULL,
    grade           INT,
    accent          VARCHAR(20)  NOT NULL DEFAULT 'sun',
    sequential_mode BOOLEAN      NOT NULL DEFAULT FALSE,
    published       BOOLEAN      NOT NULL DEFAULT FALSE,
    teacher_id      BIGINT NOT NULL REFERENCES users (id),
    created_at      TIMESTAMP NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_courses_slug ON courses (slug);

CREATE TABLE enrollments (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id  BIGINT NOT NULL REFERENCES courses (id),
    student_id BIGINT NOT NULL REFERENCES users (id),
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT ux_enrollment UNIQUE (course_id, student_id)
);

CREATE TABLE lessons (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id  BIGINT NOT NULL REFERENCES courses (id),
    title      VARCHAR(190) NOT NULL,
    position   INT NOT NULL DEFAULT 0,
    theory_md  TEXT,
    video_url  VARCHAR(500),
    published  BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE lesson_attachments (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id     BIGINT NOT NULL REFERENCES lessons (id),
    stored_path   VARCHAR(300) NOT NULL,
    original_name VARCHAR(300) NOT NULL,
    mime_type     VARCHAR(120),
    size_bytes    BIGINT
);

CREATE TABLE quizzes (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id      BIGINT NOT NULL REFERENCES lessons (id),
    title          VARCHAR(190) NOT NULL,
    time_limit_sec INT,
    max_attempts   INT NOT NULL DEFAULT 3,
    show_answers   BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ux_quiz_lesson UNIQUE (lesson_id)
);

CREATE TABLE questions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id     BIGINT NOT NULL REFERENCES quizzes (id),
    type        VARCHAR(12) NOT NULL,
    text        TEXT NOT NULL,
    answer_text VARCHAR(500),
    points      INT NOT NULL DEFAULT 1,
    position    INT NOT NULL DEFAULT 0
);

CREATE TABLE options (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id BIGINT NOT NULL REFERENCES questions (id),
    text        VARCHAR(500) NOT NULL,
    correct     BOOLEAN NOT NULL DEFAULT FALSE,
    pair_key    VARCHAR(500)
);

CREATE TABLE quiz_attempts (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id     BIGINT NOT NULL REFERENCES quizzes (id),
    student_id  BIGINT NOT NULL REFERENCES users (id),
    attempt_no  INT NOT NULL,
    started_at  TIMESTAMP NOT NULL,
    finished_at TIMESTAMP,
    score       INT,
    status      VARCHAR(20) NOT NULL,
    CONSTRAINT ux_attempt UNIQUE (quiz_id, student_id, attempt_no)
);

CREATE TABLE answers (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id    BIGINT NOT NULL REFERENCES quiz_attempts (id),
    question_id   BIGINT NOT NULL REFERENCES questions (id),
    payload       TEXT,
    correct       BOOLEAN NOT NULL DEFAULT FALSE,
    earned_points INT NOT NULL DEFAULT 0
);

CREATE TABLE homeworks (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id   BIGINT NOT NULL REFERENCES lessons (id),
    title       VARCHAR(190) NOT NULL,
    instruction TEXT,
    max_points  INT NOT NULL DEFAULT 10,
    deadline    TIMESTAMP,
    CONSTRAINT ux_hw_lesson UNIQUE (lesson_id)
);

CREATE TABLE homework_submissions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    homework_id   BIGINT NOT NULL REFERENCES homeworks (id),
    student_id    BIGINT NOT NULL REFERENCES users (id),
    text_answer   TEXT,
    stored_path   VARCHAR(300),
    original_name VARCHAR(300),
    submitted_at  TIMESTAMP NOT NULL,
    status        VARCHAR(12) NOT NULL,
    score         INT,
    feedback      TEXT,
    graded_at     TIMESTAMP,
    graded_by_id  BIGINT REFERENCES users (id),
    CONSTRAINT ux_submission UNIQUE (homework_id, student_id)
);

CREATE TABLE lesson_progress (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id    BIGINT NOT NULL REFERENCES lessons (id),
    student_id   BIGINT NOT NULL REFERENCES users (id),
    completed_at TIMESTAMP NOT NULL,
    CONSTRAINT ux_progress UNIQUE (lesson_id, student_id)
);

CREATE TABLE certificates (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id     BIGINT NOT NULL REFERENCES courses (id),
    student_id    BIGINT NOT NULL REFERENCES users (id),
    serial_number VARCHAR(40) NOT NULL,
    issued_at     TIMESTAMP NOT NULL,
    CONSTRAINT ux_certificate UNIQUE (course_id, student_id)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_certificate_serial ON certificates (serial_number);
